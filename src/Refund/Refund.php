<?php

declare(strict_types=1);

namespace Hardcastle\LedgerDirect\Core\Refund;

use Brick\Math\BigDecimal;
use Brick\Math\Exception\MathException;
use Hardcastle\LedgerDirect\Core\ChainCatalog;
use Hardcastle\LedgerDirect\Core\Xrpl\LedgerAmount;
use InvalidArgumentException;
use JsonException;
use LogicException;

/**
 * A refund: the request to pay a customer back, and what became of it on the ledger.
 *
 * LedgerDirect never sends. A refund is a payment request the merchant signs in their own
 * wallet; the core recognises the outgoing payment afterwards and only then calls it executed
 * (INVARIANTS.md, "Refund"). This record is that request, from creation to booking, and it is
 * the only place that knows what a payment on the ledger was for: which order, which purpose,
 * where the destination came from, who confirmed it. Unlike the transaction table it cannot be
 * read back from the ledger, so nothing ever empties its table.
 *
 * Immutable. A change is a new instance with the version raised by one; the repository stores it
 * only if the stored version is still the one the change started from.
 *
 * Stored as a row (toRow(), fromRow()), one column per field, so the table reads at a glance:
 * `status`, `purpose`, `destination_origin`, `matched_by` and `deviation` are plain text from
 * the constants below, never numbers.
 */
final readonly class Refund
{
    public const SCHEMA_VERSION = 1;

    /** The request exists; the merchant has not paid it yet, as far as the ledger shows. */
    public const STATUS_AWAITING_EXECUTION = 'awaiting_execution';

    /** A validated, successful payment to the destination is assigned to it. */
    public const STATUS_EXECUTED = 'executed';

    /** The merchant withdrew the request. A payment that still arrives is a finding. */
    public const STATUS_CANCELLED = 'cancelled';

    public const STATUSES = [self::STATUS_AWAITING_EXECUTION, self::STATUS_EXECUTED, self::STATUS_CANCELLED];

    /** Money for the order goes back: the one purpose that changes the order's state on the platform. */
    public const PURPOSE_ORDER_REFUND = 'order_refund';

    /** The customer paid more than was asked; the excess goes back, the order stays paid. */
    public const PURPOSE_SURPLUS_RETURN = 'surplus_return';

    /** The customer paid in an asset that was not asked for; it goes back as it came. */
    public const PURPOSE_WRONG_ASSET_RETURN = 'wrong_asset_return';

    public const PURPOSES = [self::PURPOSE_ORDER_REFUND, self::PURPOSE_SURPLUS_RETURN, self::PURPOSE_WRONG_ASSET_RETURN];

    /** Recognised by destination, tag, asset and exact amount. */
    public const MATCHED_BY_KEY = 'key';

    /** Recognised by the reference the payment carried as its `InvoiceID`. */
    public const MATCHED_BY_REFERENCE = 'reference';

    /** Assigned by the merchant, who named the transaction. */
    public const MATCHED_BY_ATTACHED = 'attached';

    public const MATCHED_BY = [self::MATCHED_BY_KEY, self::MATCHED_BY_REFERENCE, self::MATCHED_BY_ATTACHED];

    /** Paid from another account than the one the request named. */
    public const DEVIATION_OTHER_ACCOUNT = 'other_account';

    /** Delivered another amount than requested. */
    public const DEVIATION_AMOUNT = 'amount';

    /** Paid although the request had been cancelled. */
    public const DEVIATION_AFTER_CANCEL = 'after_cancel';

    /** In the order the `deviation` column lists them. */
    public const DEVIATIONS = [self::DEVIATION_OTHER_ACCOUNT, self::DEVIATION_AMOUNT, self::DEVIATION_AFTER_CANCEL];

    /** The columns of a row, in toRow()'s order; the schema is checked against this list. */
    public const COLUMNS = [
        'id', 'schema_version', 'network', 'status', 'purpose', 'platform_reference', 'source_hash', 'serial',
        'paying_account', 'destination', 'destination_tag', 'destination_origin', 'destination_attestation',
        'asset_currency', 'asset_issuer', 'amount', 'fiat_amount', 'fiat_currency', 'reference', 'reason',
        'created_at', 'created_by', 'created_ledger',
        'executed_hash', 'executed_ledger', 'executed_at', 'executed_account', 'delivered_amount',
        'matched_by', 'deviation', 'closed_at',
        'booking_claimed_until', 'booked_at', 'booking_note',
        'findings', 'open_key', 'version',
    ];

    public const MAX_PLATFORM_REFERENCE_LENGTH = 64;

    public const MAX_CREATED_BY_LENGTH = 190;

    /**
     * @param string $id 32 hex digits, generated by the core
     * @param string $platformReference whatever the platform files the refund under, e.g. the
     *     id of the order's payment transaction; the core only stores and finds by it
     * @param string $sourceHash the incoming payment this refund pays back
     * @param int $serial counts the refunds of one source payment, from 1; with the source hash
     *     it is unique, which is what makes two simultaneous requests collide
     * @param string $payingAccount the account the request asks to pay from: the one the source
     *     payment went to, not whatever the shop is configured with today
     * @param LedgerAmount $amount what was requested
     * @param string|null $fiatAmount the amount the merchant typed in the shop's currency, if they did
     * @param string $reference 64 hex digits; the payment request carries it as `invoiceid`
     * @param string|null $createdBy who created the request, as the platform names its users;
     *     required when the destination was stated or is without a tag
     * @param int $createdLedger the validated ledger when the request was created; a payment
     *     counts as its execution only in a later ledger
     * @param string|null $executedAccount the account that actually paid
     * @param LedgerAmount|null $delivered what actually arrived
     * @param list<string> $deviations DEVIATION_* in which the execution differs from the request
     * @param int|null $closedAt Unix time the request left "awaiting execution"
     * @param int|null $bookingClaimedUntil Unix time until which one process holds the right to
     *     book the execution on the platform
     * @param list<RefundFinding> $findings
     */
    private function __construct(
        public int $schemaVersion,
        public string $id,
        public string $chain,
        public string $network,
        public string $status,
        public string $purpose,
        public string $platformReference,
        public string $sourceHash,
        public int $serial,
        public string $payingAccount,
        public RefundDestination $destination,
        public LedgerAmount $amount,
        public ?string $fiatAmount,
        public ?string $fiatCurrency,
        public string $reference,
        public ?string $reason,
        public int $createdAt,
        public ?string $createdBy,
        public int $createdLedger,
        public ?string $executedHash,
        public ?int $executedLedger,
        public ?int $executedAt,
        public ?string $executedAccount,
        public ?LedgerAmount $delivered,
        public ?string $matchedBy,
        public array $deviations,
        public ?int $closedAt,
        public ?int $bookingClaimedUntil,
        public ?int $bookedAt,
        public ?string $bookingNote,
        public array $findings,
        public int $version,
    ) {
        $this->assertIdentity();
        $this->assertRequest();
        $this->assertState();
    }

    /**
     * A new request, awaiting execution.
     */
    public static function request(
        string $id,
        string $chain,
        string $network,
        string $purpose,
        string $platformReference,
        string $sourceHash,
        int $serial,
        string $payingAccount,
        RefundDestination $destination,
        LedgerAmount $amount,
        string $reference,
        int $createdAt,
        int $createdLedger,
        ?string $createdBy = null,
        ?string $reason = null,
        ?string $fiatAmount = null,
        ?string $fiatCurrency = null,
    ): self {
        return new self(
            schemaVersion: self::SCHEMA_VERSION,
            id: $id,
            chain: $chain,
            network: $network,
            status: self::STATUS_AWAITING_EXECUTION,
            purpose: $purpose,
            platformReference: $platformReference,
            sourceHash: $sourceHash,
            serial: $serial,
            payingAccount: $payingAccount,
            destination: $destination,
            amount: $amount,
            fiatAmount: $fiatAmount,
            fiatCurrency: $fiatCurrency,
            reference: $reference,
            reason: $reason,
            createdAt: $createdAt,
            createdBy: $createdBy,
            createdLedger: $createdLedger,
            executedHash: null,
            executedLedger: null,
            executedAt: null,
            executedAccount: null,
            delivered: null,
            matchedBy: null,
            deviations: [],
            closedAt: null,
            bookingClaimedUntil: null,
            bookedAt: null,
            bookingNote: null,
            findings: [],
            version: 1,
        );
    }

    public function isAwaitingExecution(): bool
    {
        return $this->status === self::STATUS_AWAITING_EXECUTION;
    }

    public function isExecuted(): bool
    {
        return $this->status === self::STATUS_EXECUTED;
    }

    public function isCancelled(): bool
    {
        return $this->status === self::STATUS_CANCELLED;
    }

    public function isBooked(): bool
    {
        return $this->bookedAt !== null;
    }

    /**
     * What this refund takes from its source payment: what arrived once it is executed, what is
     * requested while it is open, nothing once it is cancelled.
     */
    public function claimedAmount(): ?LedgerAmount
    {
        return match ($this->status) {
            self::STATUS_EXECUTED => $this->delivered,
            self::STATUS_AWAITING_EXECUTION => $this->amount,
            default => null,
        };
    }

    public function hasFindingFor(string $hash): bool
    {
        foreach ($this->findings as $finding) {
            if ($finding->hash === $hash) {
                return true;
            }
        }

        return false;
    }

    /**
     * What makes two open requests the same payment on the ledger: paying account, destination,
     * tag, asset and amount. Stored in a unique column while the request is open and null
     * afterwards, so a second open request with the same key cannot exist — a payment could not
     * be told to belong to one or the other.
     */
    public function openKey(): ?string
    {
        if (!$this->isAwaitingExecution()) {
            return null;
        }

        return hash('sha256', implode('|', [
            'ledger-direct-refund-open-v1',
            $this->chain,
            $this->network,
            $this->payingAccount,
            $this->destination->account,
            // "No tag" is not tag 0.
            $this->destination->tag === null ? 'none' : 'tag:' . $this->destination->tag,
            $this->amount->currency ?? 'native',
            $this->amount->issuer ?? '',
            $this->amount->value,
        ]));
    }

    /**
     * A validated, successful payment is this refund's execution. Possible while it awaits
     * execution, and after a cancellation: the payment happened whatever the request said, and
     * the record has to say so.
     *
     * The payment must be in the requested asset. Paid from another account, in another amount
     * or after a cancellation, it is still the execution, with the difference written down.
     *
     * @param int $executedAt Unix time of the ledger that holds the payment
     * @param string $account the account that paid
     * @param int $closedAt Unix time the core recorded the execution
     */
    public function executed(
        string $hash,
        int $ledgerIndex,
        int $executedAt,
        string $account,
        LedgerAmount $delivered,
        string $matchedBy,
        int $closedAt,
    ): self {
        if ($this->isExecuted()) {
            throw new LogicException("Refund {$this->id} is already executed.");
        }

        $deviations = [];
        if ($account !== $this->payingAccount) {
            $deviations[] = self::DEVIATION_OTHER_ACCOUNT;
        }
        if (!$delivered->equals($this->amount)) {
            $deviations[] = self::DEVIATION_AMOUNT;
        }
        if ($this->isCancelled()) {
            $deviations[] = self::DEVIATION_AFTER_CANCEL;
        }

        return $this->with([
            'status' => self::STATUS_EXECUTED,
            'executedHash' => $hash,
            'executedLedger' => $ledgerIndex,
            'executedAt' => $executedAt,
            'executedAccount' => $account,
            'delivered' => $delivered,
            'matchedBy' => $matchedBy,
            'deviations' => $deviations,
            'closedAt' => $closedAt,
        ]);
    }

    public function cancelled(int $closedAt): self
    {
        if (!$this->isAwaitingExecution()) {
            throw new LogicException("Refund {$this->id} is {$this->status} and cannot be cancelled.");
        }

        return $this->with(['status' => self::STATUS_CANCELLED, 'closedAt' => $closedAt]);
    }

    /**
     * One finding per transaction: a second one for the same hash changes nothing, and the same
     * instance comes back.
     */
    public function withFinding(RefundFinding $finding): self
    {
        if ($this->hasFindingFor($finding->hash) || $finding->hash === $this->executedHash) {
            return $this;
        }

        return $this->with(['findings' => [...$this->findings, $finding]]);
    }

    /**
     * One process takes the right to book the execution on the platform, until $until. The
     * repository's version check decides between two that try at once.
     */
    public function withBookingClaim(int $until): self
    {
        if (!$this->isExecuted() || $this->isBooked()) {
            throw new LogicException("Refund {$this->id} has nothing to book.");
        }

        return $this->with(['bookingClaimedUntil' => $until]);
    }

    /**
     * The platform has taken note of the execution (state changed, or deliberately left as it is).
     *
     * @param string|null $note what the platform did, e.g. "refunded" or "booked, state unchanged"
     */
    public function booked(int $bookedAt, ?string $note = null): self
    {
        if (!$this->isExecuted() || $this->isBooked()) {
            throw new LogicException("Refund {$this->id} has nothing to book.");
        }

        return $this->with(['bookedAt' => $bookedAt, 'bookingNote' => $note, 'bookingClaimedUntil' => null]);
    }

    /**
     * The row to store, one value per column of COLUMNS: strings, integers and null.
     *
     * @return array<string, string|int|null>
     */
    public function toRow(): array
    {
        try {
            $findings = json_encode(
                array_map(static fn (RefundFinding $finding): array => $finding->toArray(), $this->findings),
                JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES,
            );
        } catch (JsonException $exception) {
            throw new LogicException("Refund {$this->id}: its findings do not encode.", previous: $exception);
        }

        return [
            'id' => $this->id,
            'schema_version' => $this->schemaVersion,
            'network' => $this->network,
            'status' => $this->status,
            'purpose' => $this->purpose,
            'platform_reference' => $this->platformReference,
            'source_hash' => $this->sourceHash,
            'serial' => $this->serial,
            'paying_account' => $this->payingAccount,
            'destination' => $this->destination->account,
            'destination_tag' => $this->destination->tag,
            'destination_origin' => $this->destination->origin,
            'destination_attestation' => $this->destination->attestation,
            // The native asset is named for the reader; it is the null issuer that marks it.
            'asset_currency' => $this->amount->currency ?? self::nativeAsset($this->chain),
            'asset_issuer' => $this->amount->issuer,
            'amount' => $this->amount->value,
            'fiat_amount' => $this->fiatAmount,
            'fiat_currency' => $this->fiatCurrency,
            'reference' => $this->reference,
            'reason' => $this->reason,
            'created_at' => $this->createdAt,
            'created_by' => $this->createdBy,
            'created_ledger' => $this->createdLedger,
            'executed_hash' => $this->executedHash,
            'executed_ledger' => $this->executedLedger,
            'executed_at' => $this->executedAt,
            'executed_account' => $this->executedAccount,
            'delivered_amount' => $this->delivered?->value,
            'matched_by' => $this->matchedBy,
            'deviation' => implode(',', $this->deviations),
            'closed_at' => $this->closedAt,
            'booking_claimed_until' => $this->bookingClaimedUntil,
            'booked_at' => $this->bookedAt,
            'booking_note' => $this->bookingNote,
            'findings' => $findings,
            'open_key' => $this->openKey(),
            'version' => $this->version,
        ];
    }

    /**
     * Reads a stored row, strictly. A database hands integers back as strings; a digit string is
     * read as the integer it is. Anything else that does not fit — an unknown status, a damaged
     * findings column, a missing column — is refused: a refund that reads half is worse than
     * one that does not read. Columns the platform added are ignored.
     *
     * @param array<string, mixed> $row
     * @param string $chain the chain whose table the row is from; the row does not say
     */
    public static function fromRow(array $row, string $chain): self
    {
        foreach (self::COLUMNS as $column) {
            if (!array_key_exists($column, $row)) {
                throw new InvalidArgumentException("A refund row is missing the column '{$column}'.");
            }
        }

        $schemaVersion = self::rowInt($row, 'schema_version');
        if ($schemaVersion !== self::SCHEMA_VERSION) {
            throw new InvalidArgumentException(
                "Unsupported refund schema_version {$schemaVersion} (only " . self::SCHEMA_VERSION . ' is supported).'
            );
        }

        $issuer = self::rowString($row, 'asset_issuer', nullable: true);
        $currency = self::rowString($row, 'asset_currency');
        if ($issuer === null && $currency !== self::nativeAsset($chain)) {
            throw new InvalidArgumentException("A refund row names the asset '{$currency}' without an issuer.");
        }
        $amount = static fn (string $value): LedgerAmount => $issuer === null
            ? LedgerAmount::native($value)
            : LedgerAmount::issued($currency, $issuer, $value);

        $delivered = self::rowString($row, 'delivered_amount', nullable: true);
        $deviation = self::rowString($row, 'deviation');

        $refund = new self(
            schemaVersion: $schemaVersion,
            id: self::rowString($row, 'id'),
            chain: $chain,
            network: self::rowString($row, 'network'),
            status: self::rowString($row, 'status'),
            purpose: self::rowString($row, 'purpose'),
            platformReference: self::rowString($row, 'platform_reference'),
            sourceHash: self::rowString($row, 'source_hash'),
            serial: self::rowInt($row, 'serial'),
            payingAccount: self::rowString($row, 'paying_account'),
            destination: new RefundDestination(
                account: self::rowString($row, 'destination'),
                tag: self::rowInt($row, 'destination_tag', nullable: true),
                origin: self::rowString($row, 'destination_origin'),
                attestation: self::rowString($row, 'destination_attestation', nullable: true),
            ),
            amount: $amount(self::rowString($row, 'amount')),
            fiatAmount: self::rowString($row, 'fiat_amount', nullable: true),
            fiatCurrency: self::rowString($row, 'fiat_currency', nullable: true),
            reference: self::rowString($row, 'reference'),
            reason: self::rowString($row, 'reason', nullable: true),
            createdAt: self::rowInt($row, 'created_at'),
            createdBy: self::rowString($row, 'created_by', nullable: true),
            createdLedger: self::rowInt($row, 'created_ledger'),
            executedHash: self::rowString($row, 'executed_hash', nullable: true),
            executedLedger: self::rowInt($row, 'executed_ledger', nullable: true),
            executedAt: self::rowInt($row, 'executed_at', nullable: true),
            executedAccount: self::rowString($row, 'executed_account', nullable: true),
            delivered: $delivered === null ? null : $amount($delivered),
            matchedBy: self::rowString($row, 'matched_by', nullable: true),
            deviations: $deviation === '' ? [] : explode(',', $deviation),
            closedAt: self::rowInt($row, 'closed_at', nullable: true),
            bookingClaimedUntil: self::rowInt($row, 'booking_claimed_until', nullable: true),
            bookedAt: self::rowInt($row, 'booked_at', nullable: true),
            bookingNote: self::rowString($row, 'booking_note', nullable: true),
            findings: self::rowFindings($row),
            version: self::rowInt($row, 'version'),
        );

        /*
         * The open key is derived, but it is the stored value that the unique index holds. An
         * open refund whose row has no key, or another one, reserves nothing: a second refund
         * with the same key could be stored next to it.
         */
        if (self::rowString($row, 'open_key', nullable: true) !== $refund->openKey()) {
            throw new InvalidArgumentException("A refund row's open_key is not the one its refund has.");
        }

        return $refund;
    }

    /**
     * The refund for the administration's status answer or a log: nested, with every amount a
     * decimal string. It carries who created the refund and the merchant's note; it is not an
     * answer for a customer.
     *
     * @return array<string, mixed>
     */
    public function toArray(): array
    {
        return [
            'schema_version' => $this->schemaVersion,
            'id' => $this->id,
            'chain' => $this->chain,
            'network' => $this->network,
            'status' => $this->status,
            'purpose' => $this->purpose,
            'platform_reference' => $this->platformReference,
            'source_hash' => $this->sourceHash,
            'serial' => $this->serial,
            'paying_account' => $this->payingAccount,
            'destination' => $this->destination->toArray(),
            'asset' => [
                'native' => $this->amount->isNative(),
                'currency' => $this->amount->currency ?? self::nativeAsset($this->chain),
                'issuer' => $this->amount->issuer,
            ],
            'amount' => $this->amount->value,
            'fiat_amount' => $this->fiatAmount,
            'fiat_currency' => $this->fiatCurrency,
            'reference' => $this->reference,
            'reason' => $this->reason,
            'created_at' => $this->createdAt,
            'created_by' => $this->createdBy,
            'created_ledger' => $this->createdLedger,
            'execution' => !$this->isExecuted() ? null : [
                'hash' => $this->executedHash,
                'ledger_index' => $this->executedLedger,
                'executed_at' => $this->executedAt,
                'account' => $this->executedAccount,
                'delivered_amount' => $this->delivered?->value,
                'matched_by' => $this->matchedBy,
                'deviations' => $this->deviations,
            ],
            'closed_at' => $this->closedAt,
            'booking' => [
                'claimed_until' => $this->bookingClaimedUntil,
                'booked_at' => $this->bookedAt,
                'note' => $this->bookingNote,
            ],
            'findings' => array_map(static fn (RefundFinding $finding): array => $finding->toArray(), $this->findings),
            'version' => $this->version,
        ];
    }

    /**
     * The same refund with some fields changed and the version raised by one.
     *
     * @param array<string, mixed> $changes by property name
     */
    private function with(array $changes): self
    {
        $values = get_object_vars($this);
        $values['version'] = $this->version + 1;

        return new self(...array_merge($values, $changes));
    }

    private function assertIdentity(): void
    {
        if (preg_match('/^[0-9a-f]{32}\z/', $this->id) !== 1) {
            throw new InvalidArgumentException('A refund id is 32 hex digits in lower case.');
        }

        if (!in_array($this->chain, [ChainCatalog::XRPL, ChainCatalog::XAHAU], true)) {
            throw new InvalidArgumentException("Refunds exist on XRPL and XAHAU, not on '{$this->chain}'.");
        }

        if ($this->network === '' || strlen($this->network) > 16) {
            throw new InvalidArgumentException('A refund needs a network name of at most 16 characters.');
        }

        if ($this->platformReference === '' || strlen($this->platformReference) > self::MAX_PLATFORM_REFERENCE_LENGTH) {
            throw new InvalidArgumentException(
                'A refund needs a platform reference of at most ' . self::MAX_PLATFORM_REFERENCE_LENGTH . ' bytes.'
            );
        }

        foreach (['source hash' => $this->sourceHash, 'reference' => $this->reference] as $name => $value) {
            if (preg_match('/^[0-9A-F]{64}\z/', $value) !== 1) {
                throw new InvalidArgumentException("A refund's {$name} is 64 hex digits in upper case.");
            }
        }

        if ($this->serial < 1 || $this->version < 1 || $this->createdLedger < 1) {
            throw new InvalidArgumentException('A refund counts its serial, version and creation ledger from 1.');
        }

        // What a row cannot hold cannot be built either: fromRow() reads unsigned integers only.
        foreach ([$this->createdAt, $this->closedAt, $this->executedAt, $this->executedLedger, $this->bookedAt, $this->bookingClaimedUntil] as $number) {
            if ($number !== null && $number < 0) {
                throw new InvalidArgumentException("A refund's times and ledger indexes are not negative.");
            }
        }

        if ($this->createdBy !== null && strlen($this->createdBy) > self::MAX_CREATED_BY_LENGTH) {
            throw new InvalidArgumentException(
                "A refund's creator is a name of at most " . self::MAX_CREATED_BY_LENGTH . ' bytes.'
            );
        }
    }

    private function assertRequest(): void
    {
        if (!in_array($this->purpose, self::PURPOSES, true)) {
            throw new InvalidArgumentException("Unknown refund purpose '{$this->purpose}'.");
        }

        if ($this->payingAccount === '') {
            throw new InvalidArgumentException('A refund needs the account that pays it.');
        }

        if ($this->destination->account === $this->payingAccount) {
            throw new InvalidArgumentException('A refund cannot go to the account that pays it.');
        }

        if ($this->amount->issuer !== null && $this->destination->account === $this->amount->issuer) {
            throw new InvalidArgumentException("A refund cannot go to the token's issuer.");
        }

        if (!BigDecimal::of($this->amount->value)->isPositive()) {
            throw new InvalidArgumentException('A refund needs an amount above zero.');
        }

        /*
         * Whoever enters a destination can enter their own, and whoever confirms "the customer's
         * own wallet" vouches for it: a refund that rests on either names the person.
         */
        $restsOnAPerson = $this->destination->origin === RefundDestination::ORIGIN_STATED || $this->destination->attestation !== null;
        if ($restsOnAPerson && ($this->createdBy === null || trim($this->createdBy) === '')) {
            throw new InvalidArgumentException('A refund to a stated destination, or without a tag, names who created it.');
        }

        if (($this->fiatAmount === null) !== ($this->fiatCurrency === null)) {
            throw new InvalidArgumentException('A fiat amount and its currency come together or not at all.');
        }

        if ($this->fiatAmount !== null) {
            try {
                $fiat = BigDecimal::of($this->fiatAmount);
            } catch (MathException $exception) {
                throw new InvalidArgumentException("A refund's fiat amount is a decimal number, got '{$this->fiatAmount}'.", previous: $exception);
            }

            if (!$fiat->isPositive() || $this->fiatCurrency === '' || strlen((string) $this->fiatCurrency) > 8) {
                throw new InvalidArgumentException('A refund names its fiat amount above zero and in a currency of at most 8 characters.');
            }
        }
    }

    private function assertState(): void
    {
        if (!in_array($this->status, self::STATUSES, true)) {
            throw new InvalidArgumentException("Unknown refund status '{$this->status}'.");
        }

        $execution = [$this->executedHash, $this->executedLedger, $this->executedAt, $this->executedAccount, $this->delivered, $this->matchedBy];
        $given = count(array_filter($execution, static fn (mixed $value): bool => $value !== null));

        if ($this->isExecuted()) {
            if ($given !== count($execution) || $this->closedAt === null) {
                throw new InvalidArgumentException('An executed refund names hash, ledger, time, account, delivered amount and how it was matched.');
            }
            if (preg_match('/^[0-9A-F]{64}\z/', (string) $this->executedHash) !== 1) {
                throw new InvalidArgumentException("A refund's execution hash is 64 hex digits in upper case.");
            }
            if (!in_array($this->matchedBy, self::MATCHED_BY, true)) {
                throw new InvalidArgumentException("Unknown way of matching '{$this->matchedBy}'.");
            }
            if ($this->delivered === null || !$this->delivered->sameAsset($this->amount)) {
                throw new InvalidArgumentException('A refund is executed by a payment in the requested asset.');
            }
            // A refund is created after its ledger was validated, so a payment in that ledger
            // or before it was made without the request. Only a person can say it paid the
            // refund all the same (MATCHED_BY_ATTACHED); the core never concludes it.
            if ($this->matchedBy !== self::MATCHED_BY_ATTACHED && $this->executedLedger <= $this->createdLedger) {
                throw new InvalidArgumentException('A payment from before a refund was created executes it only when the merchant names it.');
            }
        } elseif ($given !== 0 || $this->deviations !== []) {
            throw new InvalidArgumentException("A refund that is {$this->status} carries no execution.");
        }

        if ($this->isAwaitingExecution() !== ($this->closedAt === null)) {
            throw new InvalidArgumentException('A refund has a closing time exactly when it no longer awaits execution.');
        }

        if ($this->deviations !== array_values(array_intersect(self::DEVIATIONS, $this->deviations))) {
            throw new InvalidArgumentException('Deviations are known ones, each once, in the order of DEVIATIONS.');
        }

        if (!$this->isExecuted() && ($this->bookedAt !== null || $this->bookingClaimedUntil !== null || $this->bookingNote !== null)) {
            throw new InvalidArgumentException('Only an executed refund is booked.');
        }

        $hashes = [];
        foreach ($this->findings as $finding) {
            if (!$finding instanceof RefundFinding) {
                throw new InvalidArgumentException('A refund keeps RefundFinding objects.');
            }
            if (isset($hashes[$finding->hash])) {
                throw new InvalidArgumentException("A refund keeps one finding per transaction; {$finding->hash} is there twice.");
            }
            $hashes[$finding->hash] = true;
        }

        if (!array_is_list($this->findings)) {
            throw new InvalidArgumentException('A refund keeps its findings as a list.');
        }
    }

    private static function nativeAsset(string $chain): string
    {
        return ChainCatalog::chain($chain)->nativeAsset;
    }

    /**
     * @param array<string, mixed> $row
     */
    private static function rowString(array $row, string $column, bool $nullable = false): ?string
    {
        $value = $row[$column];

        if ($value === null && $nullable) {
            return null;
        }

        if (!is_string($value)) {
            throw new InvalidArgumentException("A refund row's '{$column}' is not a string.");
        }

        return $value;
    }

    /**
     * @param array<string, mixed> $row
     */
    private static function rowInt(array $row, string $column, bool $nullable = false): ?int
    {
        $value = $row[$column];

        if ($value === null && $nullable) {
            return null;
        }

        if (is_int($value) && $value >= 0) {
            return $value;
        }

        // What a database driver returns for an integer column. Nothing with a sign, a
        // fraction or leading zeros passes, and nothing longer than an integer holds.
        if (is_string($value) && preg_match('/^(0|[1-9]\d{0,17})\z/', $value) === 1) {
            return (int) $value;
        }

        throw new InvalidArgumentException("A refund row's '{$column}' is not an unsigned integer.");
    }

    /**
     * @param array<string, mixed> $row
     * @return list<RefundFinding>
     */
    private static function rowFindings(array $row): array
    {
        $json = self::rowString($row, 'findings') ?? '';

        try {
            $decoded = json_decode($json, true, 16, JSON_THROW_ON_ERROR);
        } catch (JsonException $exception) {
            throw new InvalidArgumentException("A refund row's findings are not valid JSON.", previous: $exception);
        }

        // `{}` decodes to the same empty array as `[]`, and would be written back as `[]`.
        if (!is_array($decoded) || !array_is_list($decoded) || !str_starts_with(ltrim($json), '[')) {
            throw new InvalidArgumentException("A refund row's findings are not a list.");
        }

        $findings = [];
        foreach ($decoded as $finding) {
            if (!is_array($finding)) {
                throw new InvalidArgumentException("A refund row's findings hold something that is not a finding.");
            }
            $findings[] = RefundFinding::fromArray($finding);
        }

        return $findings;
    }
